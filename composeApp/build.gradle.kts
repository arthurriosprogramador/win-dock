compose.desktop {
    application {
        mainClass = "dev.windock.MainKt"
        // Footprint tuning for an always-on bar. The heap holds ~10 MB of live data, so a small cap is plenty;
        // Serial GC and C1-only JIT measured ~170 MB working set and ~40% less CPU than the JVM defaults.
        jvmArgs += listOf(
            "-Xms16m", "-Xmx128m",
            "-XX:+UseSerialGC",
            "-XX:TieredStopAtLevel=1",
            "-XX:ReservedCodeCacheSize=48m",
            "-Xss512k",
            // JNA loads native code; Java 22+ warns (and will one day refuse) unless that is allowed explicitly.
            "--enable-native-access=ALL-UNNAMED",
        )
        nativeDistributions {
            packageName = "WinDock"
            packageVersion = "1.0.0"
            vendor = "WinDock"
            description = "A themeable dock that replaces the Windows taskbar"
            // The bundled runtime only has the modules listed here (from `suggestRuntimeModules`): the weather
            // client needs java.net.http, autostart needs java.management, and Compose/JNA need jdk.unsupported.
            // jdk.localedata isn't detected but is needed: without it dates fall back to English ("TUE", not "TER").
            modules("java.instrument", "java.management", "java.net.http", "jdk.unsupported", "jdk.localedata")
            windows {
                // Per-user install: no administrator prompt, matching the per-user autostart task.
                perUserInstall = true
                menuGroup = "WinDock"
                shortcut = true
                // Must never change: it's how a new version's installer finds and replaces the old one.
                upgradeUuid = "6f1c2a8e-4b7d-4e2f-9a31-5c8d0e7b2f14"
                // Generated by tools/make_icon.py.
                iconFile.set(project.file("icons/windock.ico"))
            }
            macOS {
                packageVersion = "1.0.0"
                dmgPackageVersion = "1.0.0"
            }
            targetFormats(org.jetbrains.compose.desktop.application.dsl.TargetFormat.Msi, org.jetbrains.compose.desktop.application.dsl.TargetFormat.Dmg)
        }
    }
}
